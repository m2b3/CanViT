LATEX_DIR = Path(__file__).resolve().parent
EXPORTS_DIR = LATEX_DIR.parent / "exports"
HEADER = "% AUTO-GENERATED by generate_data.py -- do NOT edit by hand."
MIDRULE = "    \\midrule"

# Each viewing policy's label and figure colour, in the legend order of the results figure, which is the row order of
