# Each section writes its macros and row files from the exports of these exporter datasets; data.tex defines the
# macros in this order.
SECTIONS: tuple[tuple[Callable[..., None], tuple[str, ...]], ...] = (
    (ade20k, ("ade20k_seg",)),
    (in1k, ("in1k_clf_frozen", "in1k_clf_finetuned")),
    (in1k_finetune_config, ("in1k_finetune_config",)),
    (ablations, ("ablation_variants", "ablation_recon")),
    (ablation_downstream, ("ablation_variants", "ablation_seg", "ablation_in1k_clf")),
    (latency_bench, ("hw_bench",)),
    (passive_comparison, ("ade20k_seg",)),
    (dinov3_probes, ("dinov3_probe_data",)),
    (flops, ("flops",)),
    (mask_size_method, ("ade20k_iou_vs_obj",)),
    (dataset_scale, ("dataset_scale",)),
    (dataset_scale_policies, ("dataset_scale",)),
    (vpe_ablation, ("ablation_vpe_seg",)),
    (architecture_control, ("architecture_control",)),
    (coco_detection, ("coco_detection",)),
    (in1k_efficiency, ("in1k_efficiency",)),
    (learned_policies, ("learned_policies", "ade20k_seg")),
    (compute_reporting, ("compute_reporting",)),
    (pretraining_facts, ()),
)


def generate() -> Outputs:
    out = Outputs()
    for section, datasets in SECTIONS:
        section(out, *map(load, datasets))
    return out


def sources() -> list[dict]:
    """Each section with the exports it reads and the row files and macros it writes."""
    entries = []
    for section, datasets in SECTIONS:
        out = Outputs()
        section(out, *map(load, datasets))
        entries.append({"section": section.__name__, "datasets": list(datasets),
                        "row_files": list(out.row_files), "macros": list(out.macros)})
    return entries


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if a generated file differs from the exports")
    parser.add_argument("--sources", action="store_true", help="print, as JSON, what each section reads and writes")
    args = parser.parse_args()

    if args.sources:
        print(json.dumps(sources(), indent=1))
        return

    expected = generate().render()
    if args.check:
        stale = [p.name for p, text in expected.items() if not p.exists() or p.read_text() != text]
        if stale:
            sys.exit(f"Stale; run `just data` in paper/: {', '.join(stale)}")
        print(f"{len(expected)} generated files are up to date.")
        return
    for path, text in expected.items():
        path.write_text(text)
    print(f"Wrote {len(expected)} files to {LATEX_DIR}.")


if __name__ == "__main__":
    main()
