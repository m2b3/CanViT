POLICY_STYLES = json.loads((EXPORTS_DIR / "policy_styles.json").read_text())
POLICY_LABELS = {policy: style["label"] for policy, style in POLICY_STYLES["policies"].items()}
POLICY_ORDER = list(POLICY_LABELS)
