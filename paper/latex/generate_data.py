DETERMINISTIC_POLICIES = {"entropy_coarse_to_fine", "repeated_full_scene"}

SCENE_PX = 512
ADE_TABLE_GRIDS = (32, 64)
SWEEP_GRIDS = (8, 16, 32, 64)
ADE_TABLE_TIMESTEPS = (0, 1, 2, 3, 4, 9, 16, 20)
IN1K_TABLE_TIMESTEPS = (0, 1, 2, 3, 4, 5, 9, 15, 20)
# tab:ablations's first row, and qualifiers its rows add to the variants' labels (the exporter's ablation registry).
ABLATION_BASELINE_ROW = "CanViT-B (baseline)"
ABLATION_OVERVIEW_QUALIFIERS = {
    "dcan256": r"($n_h = 2$)", "qkvo-dcan256": r"($n_h = 2$)", "qkvo-dcan384": r"($n_h = 3$)", "rw-stride6": "(1R / 1W)",
}
ABLATION_METRICS = {"scene_cos_norm": "SceneNorm", "cls_cos_norm": "ClsNorm"}

BENCH_MODELS = ("canvit", "dinov3-vitb16", "dinov3-vits16")
DIGIT_WORDS = ("Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine")


@dataclass
class Outputs:
    macros: dict[str, str] = field(default_factory=dict)
    row_files: dict[str, list[str]] = field(default_factory=dict)

    def macro(self, name: str, value: str) -> None:
        assert name.isalpha(), f"LaTeX macro names are letters only: {name!r}"
        assert name not in self.macros, f"macro {name} defined twice"
        self.macros[name] = value

    def rows(self, filename: str, rows: list[str]) -> None:
        assert filename not in self.row_files, f"{filename} written twice"
        self.row_files[filename] = rows

    def render(self) -> dict[Path, str]:
        definitions = [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in self.macros.items()]
        return {
            LATEX_DIR / "data.tex": "\n".join([HEADER, "", *definitions]) + "\n",
            LATEX_DIR / "data_macros.json": json.dumps(self.macros, indent=1, sort_keys=True) + "\n",
            **{LATEX_DIR / name: "\n".join([HEADER, *rows]) + "\n" for name, rows in self.row_files.items()},
        }


def load(dataset: str) -> dict:
    """An exporter dataset's export."""
    return json.loads((EXPORTS_DIR / f"{dataset}.json").read_text())


# Rounds the JSON's decimal value half-up. f"{v:.1f}" rounds the binary float instead: 25.15 (stored as
# 25.1499...) becomes 25.1, and an exact tie such as 4.625 goes to the even neighbour, 4.62.
def fixed(v: float, decimals: int) -> str:
    return str(Decimal(str(v)).quantize(Decimal(1).scaleb(-decimals), rounding=ROUND_HALF_UP))


def fmt1(v: float) -> str:
    return fixed(v, 1)


def sci(v: float, *, significant: bool = False) -> str:
    """v as a power of ten with one decimal in the mantissa; a ".0" is dropped unless significant (a table column of
    two-figure values, where it carries precision)."""
    mantissa, exponent = f"{v:.1e}".split("e")
    return f"{mantissa if significant else mantissa.removesuffix('.0')} \\times 10^{{{int(exponent)}}}"


def thousands(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def plural(n: int, singular: str) -> str:
    return f"{n} {singular}" if n == 1 else f"{n} {singular}s"


def row(cells: list[str]) -> str:
    return "    " + " & ".join(cells) + " \\\\"


def bold(s: str) -> str:
    return f"\\textbf{{{s}}}"


def swatch(color: str) -> str:
    """A table's line swatch in a figure colour (\\policyswatch, which the preamble can switch off)."""
    return f"\\policyswatch{{{color.removeprefix('#').upper()}}}"


def policy_label(policy: str) -> str:
    label = swatch(POLICY_STYLES["policies"][policy]["color"]) + POLICY_LABELS[policy]
    return label + "$^\\dagger$" if policy in DETERMINISTIC_POLICIES else label


def by_policy_order(curves: list[dict]) -> list[dict]:
    return sorted(curves, key=lambda c: (POLICY_ORDER.index(c["policy"]), c["canvas_grid"]))


def curve(curves: list[dict], *, policy: str, canvas_grid: int) -> dict:
    [match] = [c for c in curves if c["policy"] == policy and c["canvas_grid"] == canvas_grid]
    return match


def stochastic_n_runs(curves: list[dict]) -> int:
    n_runs = {c["n_runs"] for c in curves if c["policy"] not in DETERMINISTIC_POLICIES}
    assert len(n_runs) == 1, f"stochastic policies disagree on n_runs: {sorted(n_runs)}"
    return n_runs.pop()


def printed_mean(point: dict, *, decimals: int) -> str:
    return fixed(point["mean"] * 100, decimals)


def pm_cell(mean_pct: float, half_width_pct: float, *, decimals: int, half_width_decimals: int = 2) -> str:
    """A mean over a ± half-width of its interval, stacked to keep wide tables narrow."""
    return f"\\makecell{{{fixed(mean_pct, decimals)} \\\\ $\\pm{fixed(half_width_pct, half_width_decimals)}$}}"


def stacked_label(name: str, qualifier: str) -> str:
    """A row label over its parenthesized qualifier, left-aligned: as tall as the stacked interval cells beside it."""
    return f"\\makecell[l]{{{name} \\\\ ({qualifier})}}"


def pm_inline(mean_pct: float, half_width_pct: float, *, decimals: int, half_width_decimals: int = 2) -> str:
    """A mean ± the half-width of its interval on one line, for tables narrow enough to hold it."""
    return f"{fixed(mean_pct, decimals)} $\\pm$ {fixed(half_width_pct, half_width_decimals)}"


def mean_cell(point: dict, *, n_runs: int, decimals: int, inline: bool = False) -> str:
    """A mean, with its interval's half-width when the runs differ (they agree at t = 0 for a policy that starts from
    the full scene)."""
    if n_runs < 2 or point["ci_hi"] == point["ci_lo"]:
        return printed_mean(point, decimals=decimals)
    return (pm_inline if inline else pm_cell)(point["mean"] * 100, (point["ci_hi"] - point["ci_lo"]) / 2 * 100, decimals=decimals)


def policy_table_rows(curves: list[dict], *, timesteps: tuple[int, ...], decimals: int, show_canvas: bool) -> list[str]:
    def shown(point: dict) -> Decimal:
        return Decimal(printed_mean(point, decimals=decimals))

    best = {t: max(shown(c["per_timestep"][t]) for c in curves) for t in timesteps}
    rows = []
    for c in curves:
        cells = [policy_label(c["policy"])]
        if show_canvas:
            cells.append(f"${c['canvas_grid']}^2$")
        for t in timesteps:
            point = c["per_timestep"][t]
            cell = mean_cell(point, n_runs=c["n_runs"], decimals=decimals)
            # Every cell tied with the best at the printed precision is bold: a reader compares printed values.
            cells.append(bold(cell) if shown(point) == best[t] else cell)
        rows.append(row(cells))
    return rows


def sweep(out: Outputs, curves: list[dict], *, prefix: str, decimals: int) -> list[str]:
    grids = sorted({c["canvas_grid"] for c in curves})
    policies = [p for p in POLICY_ORDER if any(c["policy"] == p for c in curves)]
    out.macro(f"{prefix}SweepN", str(stochastic_n_runs(curves)))
    out.macro(f"{prefix}SweepHeader", "\\textbf{Policy} & " + " & ".join(bold(f"$c={g}$") for g in grids))
    rows = []
    for policy in policies:
        cells = [policy_label(policy)]
        for g in grids:
            c = curve(curves, policy=policy, canvas_grid=g)
            best_point = max(c["per_timestep"], key=lambda p: p["mean"])
            cells.append(mean_cell(best_point, n_runs=c["n_runs"], decimals=decimals))
        rows.append(row(cells))
    return rows


def ade20k(out: Outputs, ade: dict) -> None:
    claims = ade["claims"]
    # The paper's ADE20K prose uses the 32x32 canvas.
    single_glimpse = claims["single_glimpse_by_grid"]["32"]
    cheapest_beat = claims["cheapest_beat_by_grid"]["32"]
    out.macro("adeBestMiou", fmt1(claims["best_miou_pct"]))
    out.macro("adeSingleGlimpseMiou", fmt1(single_glimpse["miou_pct"]))
    out.macro("adeBestPriorMiou", fmt1(claims["best_prior_miou_pct"]))
    out.macro("adeBestPriorGflops", fmt1(claims["best_prior_gflops"]))
    out.macro("adeCheapestBeatMiou", fmt1(cheapest_beat["first_beat_miou_pct"]))
    out.macro("adeCheapestBeatFlopRatio", fixed(cheapest_beat["flop_ratio"], 0))

    baselines = {(b["name"], b["num_glimpses"]): b for b in ade["baselines"]}
    out.macro("ameSetrMiou", fmt1(baselines["AME (SETR)", 8]["miou_pct"]))
    out.macro("adaglimpseEightMiou", fmt1(baselines["AdaGlimpse", 8]["miou_pct"]))

    curves = ade["policy_curves"]
    max_t = max(c["n_timesteps"] for c in curves)
    out.macro("adeMaxT", str(max_t))
    out.macro("adeLastT", str(max_t - 1))
    out.macro("bootstrapCiPct", str(round(ade["_provenance"]["ci"] * 100)))


    table_curves = by_policy_order(
        [c for c in curves if c["scene_size"] == SCENE_PX and c["canvas_grid"] in ADE_TABLE_GRIDS]
    )
    out.macro("adePolicyEvalStochN", str(stochastic_n_runs(table_curves)))
    out.rows(
        "ade20k_seg_rows.tex",
        policy_table_rows(table_curves, timesteps=ADE_TABLE_TIMESTEPS, decimals=1, show_canvas=True),
    )

    sweep_curves = [c for c in curves if c["scene_size"] == SCENE_PX and c["canvas_grid"] in SWEEP_GRIDS]
    out.rows("ade20k_canvas_sweep_rows.tex", sweep(out, sweep_curves, prefix="ade", decimals=1))

    impact_curves = [c for c in sweep_curves if c["policy"] == "coarse_to_fine"]
    out.macro("canvasGridImpactGrids", ", ".join(str(g) for g in sorted(c["canvas_grid"] for c in impact_curves)))
    out.macro("canvasGridImpactN", str(stochastic_n_runs(impact_curves)))


def in1k(out: Outputs, frozen: dict, finetuned: dict) -> None:
    for prefix, data in [("inkFrozen", frozen), ("inkFinetuned", finetuned)]:
        out.macro(f"{prefix}Best", fmt1(max(c["best_mean"] for c in data["configs"]) * 100))
    out.macro("inkMaxT", str(max(c["n_timesteps"] for c in frozen["configs"])))

    for prefix, data, filename in [
        ("inkFrozen", frozen, "in1k_clf_frozen_rows.tex"),
        ("inkFinetuned", finetuned, "in1k_clf_finetuned_rows.tex"),
    ]:
        configs = by_policy_order(data["configs"])
        out.macro(f"{prefix}StochN", str(stochastic_n_runs(configs)))
        out.rows(filename, policy_table_rows(configs, timesteps=IN1K_TABLE_TIMESTEPS, decimals=2, show_canvas=False))

    sweep_curves = frozen["configs"] + frozen["canvas_sweep"]
    out.macro("inkSweepHasData", "1" if frozen["canvas_sweep"] else "0")
    out.rows("in1k_canvas_sweep_rows.tex", sweep(out, sweep_curves, prefix="ink", decimals=2))


