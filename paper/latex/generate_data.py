def group_heading(heading: str, ncols: int) -> str:
    """A table row naming the group of rows below it."""
    return f"    \\multicolumn{{{ncols}}}{{l}}{{\\textit{{{heading}}}}} \\\\"


def only(values: Iterable) -> Any:
    distinct = set(values)
    assert len(distinct) == 1, f"expected one value, got {sorted(distinct, key=str)}"
    return distinct.pop()


def timestep_header(timesteps: Iterable[int]) -> str:
    return " & ".join(bold(f"$t{{=}}{t}$") for t in timesteps)


def interval_cell(point: dict, key: str, *, decimals: int, half_width_decimals: int = 2, inline: bool = False) -> str:
    """point[key] and its bootstrap interval, fractions printed as percentages; a zero-width interval prints alone.
    Inline puts the interval on the value's line, for narrow tables; otherwise it is stacked below."""
    half_width = (point["ci_hi"] - point["ci_lo"]) / 2 * 100
    if half_width == 0:
        return fixed(point[key] * 100, decimals)
    return (pm_inline if inline else pm_cell)(point[key] * 100, half_width, decimals=decimals, half_width_decimals=half_width_decimals)


